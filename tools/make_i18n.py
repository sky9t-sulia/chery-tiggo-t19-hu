#!/usr/bin/env python3
"""tools/i18n.tsv (English key <TAB> Ukrainian <TAB> Russian; plural forms separated by "|") -> src/i18n_tab.h"""
import sys


def c(s):
    return '"' + ''.join(ch if 32 <= ord(ch) < 127 and ch not in '"\\' else ('\\' + ch if ch in '"\\' else
                                                                            ''.join('\\x%02X' % b for b in ch.encode())) for ch in s) + '"'


rows, seen = [], set()
for n, line in enumerate(open(sys.argv[1], encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line or line.startswith('#'): continue
    p = line.split('\t')
    if len(p) != 3: sys.exit('%s:%d: 3 columns required' % (sys.argv[1], n))
    if p[0] in seen: sys.exit('%s:%d: duplicate "%s"' % (sys.argv[1], n, p[0]))
    seen.add(p[0]); rows.append(p)
print('/* generated by tools/make_i18n.py from tools/i18n.tsv - do not edit */')
print('typedef struct { const char *en; const char *uk[3]; const char *ru[3]; } i18n_row;')
print('static const i18n_row I18N[] = {')
for en, uk, ru in rows:
    f = lambda s: ', '.join(c(x) for x in (s.split('|') + [s.split('|')[-1]] * 3)[:3])
    print('    { %s, { %s }, { %s } },' % (c(en), f(uk), f(ru)))
print('};')
