#!/usr/bin/env python3
"""Camera guide line geometry from the stock cameradetect images (NAND dump: /usr/share/radar, 109 frames 720x237,
located in the 720x480 camera frame from row 192) -> src/guides_tab.h for drawing our own lines.
Frame 0..53 - left/054..001, 54 - 000 (straight), 55..108 - right/001..054; number = 54 - angle/10 (cameradetect).
Orange trajectories (one per wheel): center and thickness on rows GY0 + k*GSTEP; -1 - no line on that row.
Static lines (green / yellow / red) and distance marks - from 000.png.
Run: python3 tools/make_guides.py <path to rootfs> > src/guides_tab.h"""
import sys, glob
from PIL import Image

GY0, GSTEP, GN = 192, 4, 60          # rows 192..428


def frames(root):
    r = root + '/usr/share/radar/'
    return [r + 'left/%03d.png' % n for n in range(54, 0, -1)] + [r + '000.png'] + [r + 'right/%03d.png' % n for n in range(1, 55)]


def runs(img, want):
    """per row: pixel runs for which want(rgb) is true; y - in camera frame coordinates (+192)"""
    im = img.convert('RGBA'); w, h = im.size; px = im.load(); out = {}
    for y in range(h):
        x, row = 0, []
        while x < w:
            if px[x, y][3] and want(px[x, y][:3]):
                x0 = x
                while x < w and px[x, y][3] and want(px[x, y][:3]): x += 1
                row.append((x0, x - 1))
            else: x += 1
        if row: out[y + 192] = row
    return out


orange = lambda c: c[0] > 240 and 80 < c[1] < 225 and c[2] < 40          # (255,192,0) and blended
static = lambda c: not orange(c)


def curves(rr):
    """per-row runs -> two connected lines (by proximity of neighboring row centers); x(y), thickness(y)"""
    comps = []                                                             # [{y: (x0, x1)}]
    for y in sorted(rr):
        for x0, x1 in rr[y]:
            c = (x0 + x1) / 2
            best = None
            for k in comps:
                if y - 1 in k or y - 2 in k:
                    py = y - 1 if y - 1 in k else y - 2
                    pc = (k[py][0] + k[py][1]) / 2
                    if abs(pc - c) < 18 and (best is None or abs(pc - c) < best[0]): best = (abs(pc - c), k)
            if best: best[1][y] = (x0, x1)
            else: comps.append({y: (x0, x1)})
    comps = sorted(comps, key=len, reverse=True)[:2]
    comps.sort(key=lambda k: (k[max(k)][0] + k[max(k)][1]) / 2)          # by x at the bottom: left wheel first
    return comps


def sample(k):
    """center (in 1/4 px) and thickness on rows GY0 + i*GSTEP: average over rows y-2..y+2, then 1-2-1 smoothing"""
    xs, ws = [], []
    for i in range(GN):
        y = GY0 + i * GSTEP
        got = [k[yy] for yy in range(y - 2, y + 3) if yy in k]
        if got: xs.append(sum((a + b) / 2 for a, b in got) / len(got)); ws.append(sum(b - a + 1 for a, b in got) / len(got))
        else: xs.append(None); ws.append(0)
    sm = []
    for i, v in enumerate(xs):
        if v is None: sm.append(-1); continue
        nb = [(xs[j], wgt) for j, wgt in ((i - 1, 1), (i, 2), (i + 1, 1)) if 0 <= j < GN and xs[j] is not None]
        sm.append(round(4 * sum(a * b for a, b in nb) / sum(b for _, b in nb)))
    return sm, [round(w) for w in ws]


def fill(xs, ws):
    """gaps inside a line (-1) - linear interpolation from neighboring rows"""
    xs, ws = list(xs), list(ws)
    have = [i for i, v in enumerate(xs) if v >= 0]
    for i in range(have[0], have[-1] + 1):
        if xs[i] < 0:
            a = max(j for j in have if j < i); b = min(j for j in have if j > i); t = (i - a) / (b - a)
            xs[i] = round(xs[a] + (xs[b] - xs[a]) * t); ws[i] = round(ws[a] + (ws[b] - ws[a]) * t)
    return xs, ws


def main():
    root = sys.argv[1]
    fr = frames(root)
    tab = []
    for f in fr:
        cs = curves(runs(Image.open(f), orange))
        while len(cs) < 2: cs.append({})
        tab.append([sample(k) for k in cs])
    st = runs(Image.open(fr[54]), static)
    # static lines: left - left of the frame middle, right - right of it; rows where the line merged with a mark - from neighbors
    lines = [{y: r for y, rr in st.items() for r in rr if r[1] - r[0] < 16 and ((r[0] + r[1]) / 2 < 360) == (side == 0)}
             for side in (0, 1)]
    ticks = sorted({(y, r) for y, rr in st.items() for r in rr if r[1] - r[0] >= 16})
    print('/* generated by tools/make_guides.py from the stock cameradetect images (/usr/share/radar) - do not edit */')
    print('#define GUIDE_Y0 %d\n#define GUIDE_STEP %d\n#define GUIDE_N %d\n#define GUIDE_FRAMES %d' % (GY0, GSTEP, GN, len(fr)))
    print('/* [frame][wheel 0 left / 1 right][row]: center x in 1/4 px (-1 - none) and thickness in px, camera frame 720x480 */')
    print('static const short GUIDE_X[%d][2][%d] = {' % (len(fr), GN))
    for t in tab: print('  { {%s},\n    {%s} },' % (','.join(map(str, t[0][0])), ','.join(map(str, t[1][0]))))
    print('};\nstatic const unsigned char GUIDE_W[%d][2][%d] = {' % (len(fr), GN))
    for t in tab: print('  { {%s},\n    {%s} },' % (','.join(map(str, t[0][1])), ','.join(map(str, t[1][1]))))
    print('};')
    print('/* static lines (000.png): [left / right][row] center x in 1/4 px and thickness */')
    sx = [fill(*sample(k)) for k in lines]
    print('static const short GUIDE_SX[2][%d] = { {%s},\n  {%s} };' % (GN, ','.join(map(str, sx[0][0])), ','.join(map(str, sx[1][0]))))
    print('static const unsigned char GUIDE_SW[2][%d] = { {%s},\n  {%s} };' % (GN, ','.join(map(str, sx[0][1])), ','.join(map(str, sx[1][1]))))
    # marks: group consecutive rows into rectangles
    rects = []
    for y, (x0, x1) in ticks:
        for r in rects:
            if r[1] == y - 1 and abs(r[2] - x0) < 8: r[1] = y; r[2] = min(r[2], x0); r[3] = max(r[3], x1); break
        else: rects.append([y, y, x0, x1])
    print('/* distance marks: y0, y1, x0, x1 (top to bottom: green, yellow, red) */')
    print('static const short GUIDE_TICK[%d][4] = { %s };' % (len(rects), ', '.join('{%d,%d,%d,%d}' % tuple(r) for r in rects)))


main()
