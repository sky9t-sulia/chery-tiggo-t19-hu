# boot_static.png (design v34 Boot, without the running segment) -> boot_img.h: RLE RGB888 for huboot
import sys
from PIL import Image
im = Image.open(sys.argv[1]).convert('RGB')
w, h = im.size
px = list(im.getdata())
runs = []
i = 0
while i < len(px):
    j = i
    while j < len(px) and px[j] == px[i] and j - i < 65535: j += 1
    runs.append((j - i, px[i])); i = j
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by make_img.py from boot_static.png - do not edit */\n')
    f.write(f'#define IMG_W {w}\n#define IMG_H {h}\n#define IMG_RUNS {len(runs)}\n')
    f.write('static const unsigned short img_n[IMG_RUNS] = {' + ','.join(str(n) for n, _ in runs) + '};\n')
    f.write('static const unsigned char img_c[IMG_RUNS][3] = {' + ','.join('{%d,%d,%d}' % c for _, c in runs) + '};\n')
print(w, h, len(runs))
